#!/bin/bash

# 定义创作者列表 (格式为 "名称:ID")
creators=(
    "零度博客:625267185"
    "熠辉IndieDev:39930228"
    "小宇Boi:82363089"
    "AI超元域:3493277319825652"
    "程序员鱼皮:12890453"
    "技术爬爬虾:316183842"
    "黄益贺:322961825"
    "秋芝2046:385670211"
    "赛文乔伊:39613022"
    "朋克周:19484221"
    "AI教练振轩:3493280364890116"
    "林亦LYi:4401694"
    "老麦的工具库:486989780"
    "小Lin说:520819684"
)

# 循环执行命令
for creator in "${creators[@]}"; do
    # 拆分名称和 ID
    IFS=":" read -r name id <<< "$creator"
    
    echo "------------------------------------------------"
    echo "正在爬取博主: $name (ID: $id)"
    echo "------------------------------------------------"
    
    # 执行命令
    uv run main.py --platform bili --lt qrcode --type creator --creator_id "$id" --max_pages 3
    
    # 如果运行失败，可以选择停止脚本
    if [ $? -ne 0 ]; then
        echo "博主 $name 爬取失败，跳过或检查错误。"
    fi
done

echo "所有任务已完成！"
